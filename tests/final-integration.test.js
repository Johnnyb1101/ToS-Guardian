'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {initialize,loadInputs}=require('../tools/final-evaluation');
const C=require('../tools/final-corpus-lib');
const E=require('../tools/final-evaluation-lib');
const R=require('../tools/final-review-lib');
const {prepare,loadReview}=require('../tools/final-review');
const F=require('./final-test-fixtures');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'tg-final-integration-'));
try {
  const historical=path.join(root,'history');fs.mkdirSync(historical);
  fs.mkdirSync(path.join(historical,'sources'));fs.mkdirSync(path.join(historical,'runs'));
  fs.writeFileSync(path.join(historical,'manifest.json'),JSON.stringify({sites:{'old-corpus.com':{}}}));
  const prep=path.join(root,'prep');initialize(prep,historical);
  const f=F.makeFixture();
  f.history=loadInputs(prep).history;
  f.corpus=F.reseal({...f.corpus,historyHash:C.digest(f.history)});
  f.protocol=E.createDraftProtocol({...f,selectedLessonIds:f.treatmentRelease.config.lessons.map(l=>l.id),corpusHash:f.corpus.hash,judge:f.protocol.judge});
  f.artifacts=f.artifacts.map(a=>F.reseal({...a,protocolHash:f.protocol.hash}));
  const first=f.artifacts[0];
  const failed=F.reseal({...first,artifactId:'control-initial-failure',status:'failed',error:'Synthetic timeout retained in history'});
  const retry=F.reseal({...first,artifactId:'control-success-retry',attempt:2,previousAttemptHash:failed.hash});
  f.artifacts=[failed,f.artifacts[1],retry];
  f.grades=f.artifacts.filter(a=>a.status==='ok').map(a=>F.makeGrade(a,f.protocol));
  for(const [file,value] of Object.entries({'protocol.json':f.protocol,'corpus.json':f.corpus,'control-release.json':f.controlRelease,'treatment-release.json':f.treatmentRelease,'artifacts.json':f.artifacts,'grades.json':f.grades}))fs.writeFileSync(path.join(prep,file),JSON.stringify(value));
  const artifactFile=path.join(prep,'artifacts.json'),reviewDir=path.join(prep,'review');
  prepare(artifactFile,reviewDir,'a'.repeat(64));
  const {publicPackage,privateBindings,artifacts}=loadReview(reviewDir,artifactFile);
  assert.equal(publicPackage.items.length,2);
  const item=publicPackage.items[0];
  R.appendAttempt(reviewDir,{itemId:item.itemId,finding:'claim',verdict:'unsure',subject:item.summary,sourceEvidence:'We collect email addresses.',note:'Synthetic unresolved calibration judgment'},publicPackage,privateBindings,artifacts);
  const inputs=loadInputs(prep);
  assert.equal(inputs.humanReviews.length,1);
  const result=E.evaluatePreparation(inputs);
  assert.equal(result.evidenceValid,true,JSON.stringify(result.reasons));
  assert.equal(result.completeness.human.unsure,1);
  assert.equal(result.metrics.arms.control.failures,1);
  assert.equal(result.metrics.arms.control.attempts,2);
  assert.equal(result.promotionEligible,false);assert.equal(result.evaluationPassed,false);
  const changed=F.reseal({...retry,summary:'Altered output',summaryHash:C.hashText('Altered output')});
  fs.writeFileSync(artifactFile,JSON.stringify([failed,f.artifacts[1],changed]));
  assert.throws(()=>loadInputs(prep),/stale|tampered|differ|mismatch/);
  console.log('Integrated offline corpus/protocol/artifacts/independent grades/blinded review report: PASS; stale review rejected, unsure unresolved, real eligibility disabled');
} finally {
  const resolved=fs.realpathSync(root),temp=fs.realpathSync(os.tmpdir());
  if(!resolved.startsWith(temp+path.sep)||!path.basename(resolved).startsWith('tg-final-integration-'))throw Error('Unsafe test cleanup');
  fs.rmSync(resolved,{recursive:true,force:true});
}
